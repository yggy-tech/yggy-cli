// Package ops describes the operations `yggy api` can call. The list is
// generated from the customer OpenAPI document (apps/heimdall-api/openapi.sdk.json)
// by `go generate ./internal/ops`, and a test fails when the two drift.
package ops

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)


// Body is how an operation takes its request body.
type Body string

const (
	BodyNone      Body = ""
	BodyJSON      Body = "json"
	BodyMultipart Body = "multipart"
)

type Operation struct {
	ID          string
	Method      string
	Path        string
	Summary     string
	PathParams  []string
	QueryParams []string
	Required    []string
	Body        Body
	Stream      bool
}

// Find returns the operation with this id, ignoring case.
func Find(id string) (Operation, bool) {
	for _, op := range Operations {
		if strings.EqualFold(op.ID, id) {
			return op, true
		}
	}
	return Operation{}, false
}

type specParameter struct {
	In       string `json:"in"`
	Name     string `json:"name"`
	Required bool   `json:"required"`
}

type specOperation struct {
	OperationID string          `json:"operationId"`
	Summary     string          `json:"summary"`
	Parameters  []specParameter `json:"parameters"`
	RequestBody *struct {
		Content map[string]json.RawMessage `json:"content"`
	} `json:"requestBody"`
	Responses map[string]struct {
		Content map[string]json.RawMessage `json:"content"`
	} `json:"responses"`
}

var methods = []string{"get", "post", "put", "patch", "delete"}

// Parse reads the operations from an OpenAPI document, sorted by id.
func Parse(spec []byte) ([]Operation, error) {
	var doc struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(spec, &doc); err != nil {
		return nil, err
	}
	var out []Operation
	for path, item := range doc.Paths {
		for _, method := range methods {
			raw, ok := item[method]
			if !ok {
				continue
			}
			var so specOperation
			if err := json.Unmarshal(raw, &so); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			if so.OperationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", strings.ToUpper(method), path)
			}
			op := Operation{ID: so.OperationID, Method: strings.ToUpper(method), Path: path, Summary: so.Summary}
			for _, p := range so.Parameters {
				switch p.In {
				case "path":
					op.PathParams = append(op.PathParams, p.Name)
				case "query":
					if containsString(op.PathParams, p.Name) {
						continue
					}
					op.QueryParams = append(op.QueryParams, p.Name)
					if p.Required {
						op.Required = append(op.Required, p.Name)
					}
				}
			}
			if so.RequestBody != nil {
				if _, ok := so.RequestBody.Content["multipart/form-data"]; ok {
					op.Body = BodyMultipart
				} else if _, ok := so.RequestBody.Content["application/json"]; ok {
					op.Body = BodyJSON
				}
			}
			for _, res := range so.Responses {
				if _, ok := res.Content["text/event-stream"]; ok {
					op.Stream = true
				}
			}
			out = append(out, op)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

func containsString(list []string, value string) bool {
	for _, item := range list {
		if item == value {
			return true
		}
	}
	return false
}

// Source renders operations as the Go file `go generate` writes.
func Source(operations []Operation) string {
	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n// Source: apps/heimdall-api/openapi.sdk.json\n\npackage ops\n\nvar Operations = []Operation{\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, Summary: %q", op.ID, op.Method, op.Path, op.Summary)
		writeList(&b, "PathParams", op.PathParams)
		writeList(&b, "QueryParams", op.QueryParams)
		writeList(&b, "Required", op.Required)
		if op.Body != BodyNone {
			fmt.Fprintf(&b, ", Body: %q", string(op.Body))
		}
		if op.Stream {
			b.WriteString(", Stream: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func writeList(b *strings.Builder, field string, values []string) {
	if len(values) == 0 {
		return
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	fmt.Fprintf(b, ", %s: []string{%s}", field, strings.Join(quoted, ", "))
}
